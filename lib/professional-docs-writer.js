const fs = require("fs/promises");
const path = require("path");
const {
  isInside,
  projectedRealPath,
  realpathOrNull,
} = require("./portfolio-safe-fs");
const { byText } = require("./portfolio-util");

// Ownership-safe writes for `xfeat scan`. A generated page starts with the
// marker line; any other existing file at a generated path belongs to the
// repository's authors and is left untouched.

const GENERATED_MARKER =
  "<!-- xfeat:generated. xfeat scan overwrites this file; delete this line to keep manual edits. -->";
const MARKER_PREFIX = "<!-- xfeat:generated";
// Opening lines that every scan wrote before markers existed: the title, then
// one of these intros. Current pages use different intros, so a page whose
// marker was deleted never matches and stays with its authors.
const LEGACY_INTROS = new Set([
  "Generated by `xfeat scan` from repository source evidence.",
  "Generated reference documentation from source evidence.",
  "Start here when joining the repository or preparing a code change.",
  "Generated task guide from package metadata and repository tests.",
  "Architecture decision records found in this repository.",
  "Complete generated claim inventory with source evidence.",
  "Complete source-file inventory scanned by `xfeat scan`.",
  "Complete exported-symbol inventory detected from source.",
  "Complete cross-file and cross-package edge inventory detected by `xfeat scan`.",
]);

function isLegacyPage(text) {
  const [title = "", intro = ""] = text
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);
  if (title === "# xfeat Report") return intro.startsWith("- Source files:");
  return title.startsWith("# ") && LEGACY_INTROS.has(intro);
}

async function readPreviousStatus(targetDir) {
  try {
    const status = JSON.parse(
      await fs.readFile(path.join(targetDir, ".xfeat", "status.json"), "utf8"),
    );
    return status && typeof status === "object" ? status : null;
  } catch {
    return null;
  }
}

// Why a path must not be written: it resolves outside the repository through
// a symlinked folder, or it exists and is not a regular file (a symlink,
// directory, or device). Null when the path is safe to write.
async function unsafeReason(realRoot, absolutePath) {
  if (!isInside(await projectedRealPath(absolutePath), realRoot)) {
    return "resolves outside the repository";
  }
  try {
    if (!(await fs.lstat(absolutePath)).isFile()) return "not a regular file";
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  return null;
}

async function skipReason(realRoot, absolutePath) {
  const unsafe = await unsafeReason(realRoot, absolutePath);
  if (unsafe) return unsafe;
  let text;
  try {
    text = await fs.readFile(absolutePath, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
  const firstLine = text
    .replace(/^\uFEFF/, "")
    .split("\n", 1)[0]
    .trim();
  if (firstLine.startsWith(MARKER_PREFIX) || isLegacyPage(text)) return null;
  return "not generated by xfeat";
}

function createDocWriter(targetDir) {
  const realRootPromise = realpathOrNull(targetDir);
  const realRoot = async () =>
    (await realRootPromise) || path.resolve(targetDir);
  const written = [];
  const skipped = [];
  const skip = (relativePath, reason) => {
    skipped.push({ path: relativePath, reason });
    return false;
  };
  return {
    // Creates a folder only when it resolves inside the repository.
    async ensureDir(relativeDir) {
      const absoluteDir = path.join(targetDir, relativeDir);
      if (!isInside(await projectedRealPath(absoluteDir), await realRoot())) {
        return skip(relativeDir, "resolves outside the repository");
      }
      await fs.mkdir(absoluteDir, { recursive: true });
      return true;
    },
    // Creates an xfeat-owned file that must never replace anything, even a
    // dangling symlink: "wx" fails when any entry exists at the path.
    async createIfMissing(relativePath, body) {
      const absolutePath = path.join(targetDir, relativePath);
      const reason = await unsafeReason(await realRoot(), absolutePath);
      if (reason === "resolves outside the repository") {
        return skip(relativePath, reason);
      }
      try {
        await fs.writeFile(absolutePath, body, {
          encoding: "utf8",
          flag: "wx",
        });
        return true;
      } catch (error) {
        if (error.code === "EEXIST") return false;
        throw error;
      }
    },
    // Rewrites xfeat-owned state such as .xfeat/status.json, refusing links.
    async writeState(relativePath, body) {
      const absolutePath = path.join(targetDir, relativePath);
      const reason = await unsafeReason(await realRoot(), absolutePath);
      if (reason) return skip(relativePath, reason);
      await fs.mkdir(path.dirname(absolutePath), { recursive: true });
      await fs.writeFile(absolutePath, body, "utf8");
      return true;
    },
    async write(docPath, body) {
      const absolutePath = path.join(targetDir, docPath);
      const reason = await skipReason(await realRoot(), absolutePath);
      if (reason) return skip(docPath, reason);
      await fs.mkdir(path.dirname(absolutePath), { recursive: true });
      await fs.writeFile(
        absolutePath,
        `${GENERATED_MARKER}\n\n${body}`,
        "utf8",
      );
      written.push(docPath);
      return true;
    },
    written: () => [...new Set(written)].sort(),
    skipped: () => [...skipped].sort((a, b) => byText(a.path, b.path)),
  };
}

module.exports = {
  GENERATED_MARKER,
  createDocWriter,
  readPreviousStatus,
};
