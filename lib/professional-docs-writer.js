const fs = require("fs/promises");
const path = require("path");
const {
  isInside,
  projectedRealPath,
  realpathOrNull,
} = require("./portfolio-safe-fs");
const { byText } = require("./portfolio-util");

// Ownership-safe writes for `xfeat scan`. A generated page starts with the
// marker line; any other existing file at a generated path belongs to the
// repository's authors and is left untouched.

const GENERATED_MARKER =
  "<!-- xfeat:generated. xfeat scan overwrites this file; delete this line to keep manual edits. -->";
const MARKER_PREFIX = "<!-- xfeat:generated";
// Scans before markers existed always wrote the report but never listed it.
const LEGACY_REPORT = "xfeat-report.md";

async function readPreviousStatus(targetDir) {
  try {
    const status = JSON.parse(
      await fs.readFile(path.join(targetDir, ".xfeat", "status.json"), "utf8"),
    );
    return status && typeof status === "object" ? status : null;
  } catch {
    return null;
  }
}

// Pages a pre-marker scan wrote. Once a status records the marker, only the
// marker line proves ownership, so deleting it hands the page to its authors.
function legacyDocuments(status) {
  if (!status || status.generatedMarker) return new Set();
  const documents = Array.isArray(status.documents) ? status.documents : [];
  return new Set([...documents, LEGACY_REPORT]);
}

async function skipReason(realRoot, absolutePath, docPath, legacy) {
  if (!isInside(await projectedRealPath(absolutePath), realRoot)) {
    return "resolves outside the repository";
  }
  let stat;
  try {
    stat = await fs.lstat(absolutePath);
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
  if (!stat.isFile()) return "not a regular file";
  const text = await fs.readFile(absolutePath, "utf8");
  const firstLine = text
    .replace(/^\uFEFF/, "")
    .split("\n", 1)[0]
    .trim();
  if (firstLine.startsWith(MARKER_PREFIX)) return null;
  if (legacy.has(docPath)) return null;
  return "not generated by xfeat";
}

function createDocWriter(targetDir, previousStatus) {
  const legacy = legacyDocuments(previousStatus);
  const realRoot = realpathOrNull(targetDir);
  const written = [];
  const skipped = [];
  return {
    async write(docPath, body) {
      const absolutePath = path.join(targetDir, docPath);
      const reason = await skipReason(
        (await realRoot) || path.resolve(targetDir),
        absolutePath,
        docPath,
        legacy,
      );
      if (reason) {
        skipped.push({ path: docPath, reason });
        return false;
      }
      await fs.mkdir(path.dirname(absolutePath), { recursive: true });
      await fs.writeFile(
        absolutePath,
        `${GENERATED_MARKER}\n\n${body}`,
        "utf8",
      );
      written.push(docPath);
      return true;
    },
    written: () => [...new Set(written)].sort(),
    skipped: () => [...skipped].sort((a, b) => byText(a.path, b.path)),
  };
}

module.exports = {
  GENERATED_MARKER,
  createDocWriter,
  readPreviousStatus,
};
